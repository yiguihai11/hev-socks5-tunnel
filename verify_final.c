#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <arpa/inet.h>

typedef struct {
    uint16_t id;
    uint16_t flags;
    uint16_t qdcount;
    uint16_t ancount;
    uint16_t nscount;
    uint16_t arcount;
} __attribute__((packed)) DNSHeader;

int main() {
    /* 测试2原始数据 */
    uint8_t orig2[] = {
        0x12,0x34,0x81,0x80, 0x00,0x01,0x00,0x03, 0x00,0x00,0x00,0x00,
        0x03,0x77,0x77,0x77, 0x07,0x65,0x78,0x61, 0x6d,0x70,0x6c,0x65, 0x03,0x63,0x6f,0x6d, 0x00,
        0x00,0x01,0x00,0x01,
        0xc0,0x0c,0x00,0x05,0x00,0x01,0x00,0x00,0x01,0x2c,0x00,0x0e,
        0x04,0x63,0x6e,0x61,0x6d,0x65, 0x07,0x65,0x78,0x61,0x6d,0x70,0x6c,0x65, 0x03,0x63,0x6f,0x6d, 0x00,
        0xc0,0x2a,0x00,0x01,0x00,0x01,0x00,0x00,0x01,0x2c,0x00,0x04,0xb6,0x83,0x1a,0xe7,
        0xc0,0x2a,0x00,0x01,0x00,0x01,0x00,0x00,0x01,0x2c,0x00,0x04,0x05,0x06,0x07,0x08,
    };
    
    printf("原始数据位置59-60: %02x %02x\n", orig2[59], orig2[60]);
    printf("原始数据位置42: %02x\n", orig2[42]);
    
    /* 修复后的数据 */
    uint8_t fixed[96];
    size_t fixed_len = 33 + 26 + 16;
    
    memcpy(fixed, orig2, 33);
    memcpy(fixed + 33, orig2 + 33, 26);
    memcpy(fixed + 59, orig2 + 59, 16);
    
    DNSHeader *hdr = (DNSHeader *)fixed;
    hdr->ancount = htons(2);
    
    printf("\n修复后位置59-60: %02x %02x\n", fixed[59], fixed[60]);
    printf("修复后位置42: %02x\n", fixed[42]);
    
    int ptr = ((fixed[59] & 0x3F) << 8) | fixed[60];
    printf("\nAnswer2压缩指针: 0x%02x%02x -> 位置%d\n", fixed[59], fixed[60], ptr);
    
    if (ptr >= 12 && ptr < 59) {
        printf("✓ 有效: 指向Query Section\n");
    } else if (ptr >= 59 && ptr < fixed_len) {
        printf("✓ 有效: 指向Answer1内部\n");
    } else {
        printf("❌ 无效\n");
    }
    
    printf("\n修复后数据:\n");
    for (int i = 0; i < fixed_len; i++) {
        printf("%02x ", fixed[i]);
        if ((i+1) % 16 == 0) printf("\n");
    }
    printf("\n");
    
    return 0;
}
